/**
 * Entretien professionnel — banque de questions, relances et grilles.
 *
 * Règle absolue tenue ici : l'application ne rédige jamais une expérience à la
 * place de l'utilisatrice. Les « trames » sont des cases vides accompagnées
 * d'une aide à la réflexion ; aucun exemple de vécu n'est pré-rempli.
 *
 * Le barème /20 retenu (parcours 4, motivation 4, connaissance du métier et de
 * la formation 4, analyse et posture 4, organisation et communication 4) est un
 * choix pédagogique de cette application, pas le barème d'un jury.
 */

import type { Criterion, OralQuestion } from '../types'

const C = {
  parcours: {
    id: 'parcours',
    label: 'Parcours et expériences',
    points: 4,
    evidence: [
      'Des faits précis sont cités (situations, durées, responsabilités réelles)',
      'Le rôle exact qui a été le vôtre est distingué de celui de l’équipe',
      'Aucun élément identifiant une personne accompagnée',
    ],
  },
  motivation: {
    id: 'motivation',
    label: 'Motivation et projet',
    points: 4,
    evidence: [
      'Le « pourquoi infirmière » s’appuie sur des faits vécus, pas sur des formules',
      'Le « pourquoi maintenant » est expliqué',
      'Le projet est cohérent avec le parcours décrit',
    ],
  },
  metier: {
    id: 'metier',
    label: 'Connaissance du métier et de la formation',
    points: 4,
    evidence: [
      'Les différences entre les deux métiers sont nommées concrètement',
      'La formation est connue dans ses grandes lignes (alternance cours / stages)',
      'Ce qui reste à découvrir est reconnu sans être masqué',
    ],
  },
  analyse: {
    id: 'analyse',
    label: 'Analyse et posture',
    points: 4,
    evidence: [
      'Les faits sont distingués des interprétations',
      'Une limite personnelle ou une erreur est reconnue avec ce qu’elle a appris',
      'Aucun jugement porté sur une personne accompagnée ou une collègue',
    ],
  },
  organisation: {
    id: 'organisation',
    label: 'Organisation du projet et communication',
    points: 4,
    evidence: [
      'La réponse est structurée et tient dans le temps annoncé',
      'Les contraintes concrètes sont anticipées (transport, horaires, financement)',
      'Ce qui est confirmé est distingué de ce qui reste à confirmer',
    ],
  },
} satisfies Record<string, Criterion>

/** Trame de récit d'expérience, commune aux questions qui en demandent une. */
