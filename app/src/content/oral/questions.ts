type Spec = {
  id: string
  skill: string
  axis: string
  q: string
  level?: 'decouverte' | 'entrainement' | 'epreuve'
  follow: string[]
  looks: string[]
  avoid: string[]
  frame?: typeof FRAME_RECIT
  crit: Criterion[]
  sec?: number
}

const build = (s: Spec): OralQuestion => ({
  id: s.id,
  skillId: s.skill,
  axis: s.axis,
  question: s.q,
  level: s.level ?? 'entrainement',
  followUps: s.follow,
  looksFor: s.looks,
  avoid: s.avoid,
  frame: s.frame ?? FRAME_SIMPLE,
  criteria: s.crit,
  seconds: s.sec ?? 180,
  review: 'relu-par-le-modele',
})

